<?php

declare(strict_types=1);

namespace ChrisBassi\PixBrCode;

/**
 * Normaliza textos para o BR Code: remove acentos e qualquer caractere fora do ASCII imprimível.
 */
final class Text
{
    private const MAP = [
        'á' => 'a', 'à' => 'a', 'â' => 'a', 'ã' => 'a', 'ä' => 'a',
        'é' => 'e', 'è' => 'e', 'ê' => 'e', 'ë' => 'e',
        'í' => 'i', 'ì' => 'i', 'î' => 'i', 'ï' => 'i',
        'ó' => 'o', 'ò' => 'o', 'ô' => 'o', 'õ' => 'o', 'ö' => 'o',
        'ú' => 'u', 'ù' => 'u', 'û' => 'u', 'ü' => 'u',
        'ç' => 'c', 'ñ' => 'n',
        'Á' => 'A', 'À' => 'A', 'Â' => 'A', 'Ã' => 'A', 'Ä' => 'A',
        'É' => 'E', 'È' => 'E', 'Ê' => 'E', 'Ë' => 'E',
        'Í' => 'I', 'Ì' => 'I', 'Î' => 'I', 'Ï' => 'I',
        'Ó' => 'O', 'Ò' => 'O', 'Ô' => 'O', 'Õ' => 'O', 'Ö' => 'O',
        'Ú' => 'U', 'Ù' => 'U', 'Û' => 'U', 'Ü' => 'U',
        'Ç' => 'C', 'Ñ' => 'N',
    ];

    public static function clean(string $text, int $maxLength): string
    {
        $text = strtr($text, self::MAP);
        $text = preg_replace('/[^\x20-\x7E]/', '', $text) ?? '';
        $text = preg_replace('/\s+/', ' ', trim($text)) ?? '';

        return rtrim(substr($text, 0, $maxLength));
    }
}
